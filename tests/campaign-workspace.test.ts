import assert from 'node:assert/strict';
import {campaignAnchor,campaignMetrics,campaignTasks,scopeCampaignRows} from '../src/campaignWorkspace.ts';
import {setTaskStatus,shiftTask,type PortfolioRow} from '../src/portfolio.ts';
import type {Task} from '../src/work.ts';
const task=(id:string,patch:Partial<Task>={}):Task=>({id,title:id,campaign:'campaign-a',discipline:'Marketing',due:'2026-11-10',start:'2026-11-08',priority:'Medium',done:false,...patch});
const tasks=[task('open'),task('done',{done:true,milestone:true}),task('archived',{archived:true}),task('other',{campaign:'campaign-b'}),task('undated',{due:'',start:undefined})];
assert.equal(campaignTasks(tasks,'campaign-a').length,3);
assert.equal(campaignAnchor(tasks,'campaign-a','2026-11-21'),'2026-11-08');
assert.equal(campaignAnchor([task('undated',{due:''})],'campaign-a','2026-11-21'),'2026-11-21');
assert.deepEqual(campaignMetrics(campaignTasks(tasks,'campaign-a'),'2026-11-21'),{total:3,completed:1,progress:33,overdue:1,unscheduled:1,milestones:[tasks[1]]});
const row=(workspace:string,t:Task):PortfolioRow=>({workspace,task:t,company:workspace,channel:'Website',campaignName:'Campaign',projectName:''});
const scoped=scopeCampaignRows([row('company-a',tasks[0]),row('company-b',tasks[0]),row('company-a',tasks[3]),row('company-a',tasks[2])],'company-a','campaign-a');
assert.deepEqual(scoped.map(row=>row.task.id),['open']);
const changed=setTaskStatus(tasks,'open','In progress','2026-11-21T12:00:00Z').map(t=>t.id==='open'?shiftTask(t,2):t);
assert.equal(changed[0].due,'2026-11-12');
assert.equal(changed[0].start,'2026-11-10');
assert.equal(changed[0].status,'In progress');
assert.equal(changed[3],tasks[3]);
console.log('Campaign scoping, summaries and shared task updates passed.');
